    print(f"parameter_count={parameter_count}")  # noqa: T201
    print(f"compressed_size_bytes={artifact_bytes}")  # noqa: T201
    print(f"artifact_bits_per_parameter={artifact_bits_per_parameter:.6f}")  # noqa: T201
    return 0


