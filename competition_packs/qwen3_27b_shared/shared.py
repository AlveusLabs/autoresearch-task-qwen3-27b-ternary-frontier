def _non_negative_int(value: Any, *, field_name: str) -> int:
    try:
        parsed = int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field_name} must be a non-negative integer") from exc
    if parsed < 0:
        raise ValueError(f"{field_name} must be a non-negative integer")
    return parsed


def _positive_float(value: Any, *, field_name: str) -> float:
    try:
        parsed = float(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{field_name} must be a positive finite number") from exc
    if not math.isfinite(parsed) or parsed <= 0.0:
        raise ValueError(f"{field_name} must be a positive finite number")
    return parsed


def _validate_q4_rescue_bits(bits_per_parameter: float) -> None:
    if abs(float(bits_per_parameter) - DEFAULT_RESCUE_BITS_PER_PARAMETER) > 1e-12:
        raise ValueError("rescue_values_q4 requires rescue_bits_per_parameter=4.0")


def _validate_rescue_scale_group_size(value: Any, *, source: str) -> int:
    try:
        parsed = int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(f"{source}.rescue_scale_group_size must be {Q4_RESCUE_SCALE_GROUP_SIZE}") from exc
    if parsed != Q4_RESCUE_SCALE_GROUP_SIZE:
        raise ValueError(f"{source}.rescue_scale_group_size must be {Q4_RESCUE_SCALE_GROUP_SIZE}")
    return parsed


def _q4_rescue_scale_count(value_count: int, *, group_size: int = Q4_RESCUE_SCALE_GROUP_SIZE) -> int:
    if value_count <= 0:
        return 0
    return int(math.ceil(value_count / float(group_size)))


def _q4_rescue_scale_bits(value_count: int, *, group_size: int = Q4_RESCUE_SCALE_GROUP_SIZE) -> int:
    return _q4_rescue_scale_count(value_count, group_size=group_size) * Q4_RESCUE_SCALE_BITS


def _fp16_json_float(value: float) -> float:
    return float(np.float16(value))


def _encode_q4_rescue_payload(values: np.ndarray) -> tuple[list[int], list[float], int]:
    source = np.asarray(values, dtype=np.float64)
    if source.size == 0:
        return [], [], Q4_RESCUE_SCALE_GROUP_SIZE
    qmax = 7
    codes = np.zeros(source.shape, dtype=np.int64)
    scales: list[float] = []
    for start in range(0, int(source.size), Q4_RESCUE_SCALE_GROUP_SIZE):
        stop = min(start + Q4_RESCUE_SCALE_GROUP_SIZE, int(source.size))
        chunk = source[start:stop]
        scale = float(np.max(np.abs(chunk))) / qmax
        if not math.isfinite(scale) or scale <= 0.0:
            scale = 1.0
        scale = _fp16_json_float(scale)
        if not math.isfinite(scale) or scale <= 0.0:
            scale = 1.0
        codes[start:stop] = np.clip(np.round(chunk / scale), -qmax, qmax).astype(np.int64)
        scales.append(float(scale))
    return [int(value) for value in codes], scales, Q4_RESCUE_SCALE_GROUP_SIZE


def _decode_q4_rescue_payload(
    *,
    raw_values: Any,
    raw_scales: Any,
    raw_scale_group_size: Any,
    raw_quantization: Any,
    expected_count: int,
    bits_per_parameter: float,
    source: str,
) -> np.ndarray:
    _validate_q4_rescue_bits(bits_per_parameter)
    quantization = str(raw_quantization or Q4_RESCUE_QUANTIZATION).strip().lower()
    scaled_aliases = {
        Q4_RESCUE_QUANTIZATION,
        "q4_scaled",
        "int4_scaled",
        "signed_int4_scaled",
        "q4_symmetric_int_scaled",
    }
    if quantization not in scaled_aliases:
        raise ValueError(f"{source}.rescue_quantization must be {Q4_RESCUE_QUANTIZATION}")
    if expected_count == 0:
        if raw_values not in (None, []):
            raise ValueError(f"{source}.rescue_values_q4 must be empty when no rescue values are selected")
        if raw_scales not in (None, []):
            raise ValueError(f"{source}.rescue_scales must be empty when no rescue values are selected")
        return np.asarray([], dtype=np.float64)
    if not isinstance(raw_values, list):
        raise ValueError(f"{source}.rescue_values_q4 must be a list of signed q4 integer codes")
    if len(raw_values) != expected_count:
        raise ValueError(
            f"{source}.rescue_values_q4 length {len(raw_values)} does not match rescue_count {expected_count}"
        )
    codes: list[int] = []
    for index, raw_code in enumerate(raw_values):
        if isinstance(raw_code, bool) or not isinstance(raw_code, int):
            raise ValueError(f"{source}.rescue_values_q4[{index}] must be an integer")
        if raw_code < -7 or raw_code > 7:
            raise ValueError(f"{source}.rescue_values_q4[{index}] must be in signed q4 range [-7, 7]")
        codes.append(int(raw_code))
    code_array = np.asarray(codes, dtype=np.float64)

    group_size = _validate_rescue_scale_group_size(
        Q4_RESCUE_SCALE_GROUP_SIZE if raw_scale_group_size is None else raw_scale_group_size,
        source=source,
    )
    expected_scale_count = _q4_rescue_scale_count(expected_count, group_size=group_size)
    if not isinstance(raw_scales, list):
        raise ValueError(f"{source}.rescue_scales must be a list of fp16 group scales")
    if len(raw_scales) != expected_scale_count:
        raise ValueError(
            f"{source}.rescue_scales length {len(raw_scales)} does not match "
            f"q4 group count {expected_scale_count}"
        )
    scales: list[float] = []
    for index, raw_group_scale in enumerate(raw_scales):
        scale = _positive_float(raw_group_scale, field_name=f"{source}.rescue_scales[{index}]")
        fp16_scale = _fp16_json_float(scale)
        if not math.isclose(scale, fp16_scale, rel_tol=1e-3, abs_tol=1e-8):
            raise ValueError(f"{source}.rescue_scales[{index}] must be fp16-representable")
        scales.append(fp16_scale)
    scale_array = np.asarray(scales, dtype=np.float64)
    group_index = np.arange(expected_count, dtype=np.int64) // group_size
    return code_array * scale_array[group_index]


def _validate_declared_accounting(artifact: dict[str, Any], summary: dict[str, Any]) -> None:
    accounting = artifact.get("accounting")
    if accounting is None:
        return
    if not isinstance(accounting, dict):
        raise ValueError("artifact.accounting must be an object")

    int_fields = {
        "parameter_count": "parameter_count",
        "compressed_bits": "compressed_bits",
        "compressed_size_bytes": "compressed_size_bytes",
        "high_precision_count": "total_high_precision_count",
        "rescue_count": "total_high_precision_count",
        "total_rescue_count": "total_rescue_count",
    }
    for declared_key, computed_key in int_fields.items():
        if declared_key not in accounting:
            continue
        declared = _non_negative_int(accounting[declared_key], field_name=f"artifact.accounting.{declared_key}")
        computed = int(summary[computed_key])
        if declared != computed:
            raise ValueError(
                f"artifact.accounting.{declared_key}={declared} does not match validator computed {computed}"
            )

    float_fields = {
        "overall_high_precision_fraction": "overall_high_precision_fraction",
        "high_precision_fraction": "overall_high_precision_fraction",
        "rescue_fraction": "overall_high_precision_fraction",
        "overall_rescue_fraction": "overall_rescue_fraction",
    }
    for declared_key, computed_key in float_fields.items():
        if declared_key not in accounting:
            continue
        try:
            declared = float(accounting[declared_key])
        except (TypeError, ValueError) as exc:
            raise ValueError(f"artifact.accounting.{declared_key} must be a finite number") from exc
        computed = float(summary[computed_key])
        if not math.isfinite(declared) or not math.isclose(declared, computed, rel_tol=1e-6, abs_tol=1e-9):
            raise ValueError(
                f"artifact.accounting.{declared_key}={declared:.12g} does not match "
                f"validator computed {computed:.12g}"
            )


def _accounting_entries_from_artifact(artifact: dict[str, Any], plans: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    accounting = artifact.get("accounting")
    if accounting is not None:
        if not isinstance(accounting, dict):
            raise ValueError("artifact.accounting must be an object")
        raw_entries = accounting.get("extra_entries", [])
        if not isinstance(raw_entries, list):
            raise ValueError("artifact.accounting.extra_entries must be a list")
        for entry in raw_entries:
            if not isinstance(entry, dict):
                raise ValueError("artifact.accounting.extra_entries entries must be objects")
            entries.append(dict(entry, _source="artifact.accounting.extra_entries"))

    for layer_name, plan in plans.items():
        raw_entries = plan.get("extra_components", plan.get("accounting_entries", []))
        if raw_entries is None:
            continue
        if not isinstance(raw_entries, list):
            raise ValueError(f"artifact layer {layer_name} extra_components must be a list")
        for entry in raw_entries:
            if not isinstance(entry, dict):
                raise ValueError(f"artifact layer {layer_name} extra_components entries must be objects")
            entries.append(dict(entry, layer=layer_name, _source=f"artifact.layers[{layer_name}].extra_components"))
    return entries


def _summarize_extra_accounting_entries(entries: list[dict[str, Any]]) -> dict[str, Any]:
    allowed_roles = {
        "binary",
        "ternary",
        "quantized",
        "residual",
        "scale",
        "side",
        "metadata",
        "high_precision",
        "full_precision",
        "rescue",
        "q4_rescue",
        "rescue_q4",
    }
    rows: list[dict[str, Any]] = []
    total_parameter_count = 0
    total_compressed_bits = 0
    total_high_precision_count = 0
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            raise ValueError("artifact accounting entries must be objects")
        source = str(entry.get("_source") or "artifact accounting")
        name = str(entry.get("name") or f"extra_{index}").strip() or f"extra_{index}"
        role = str(entry.get("role") or "side").strip().lower()
        if role not in allowed_roles:
            raise ValueError(f"{source}.{name} uses unsupported accounting role: {role}")
        parameter_count = _non_negative_int(
            entry.get("parameter_count"),
            field_name=f"{source}.{name}.parameter_count",
        )
        if parameter_count == 0:
            raise ValueError(f"{source}.{name}.parameter_count must be greater than zero")

        counts_toward_rescue = bool(entry.get("counts_toward_rescue", False)) or role in {
            "high_precision",
            "full_precision",
            "rescue",
            "q4_rescue",
            "rescue_q4",
        }

        if "compressed_bits" in entry:
            compressed_bits = _non_negative_int(
                entry["compressed_bits"],
                field_name=f"{source}.{name}.compressed_bits",
            )
        elif "size_bytes" in entry:
            compressed_bits = 8 * _non_negative_int(
                entry["size_bytes"],
                field_name=f"{source}.{name}.size_bytes",
            )
        elif "bits_per_parameter" in entry:
            bits_per_parameter = _positive_float(
                entry["bits_per_parameter"],
                field_name=f"{source}.{name}.bits_per_parameter",
            )
            compressed_bits = int(math.ceil(parameter_count * bits_per_parameter))
        elif counts_toward_rescue:
            bits_per_parameter = DEFAULT_RESCUE_BITS_PER_PARAMETER
            compressed_bits = int(math.ceil(parameter_count * bits_per_parameter))
        else:
            raise ValueError(
                f"{source}.{name} must declare compressed_bits, size_bytes, or bits_per_parameter"
            )

        effective_bits_per_parameter = compressed_bits / max(1, parameter_count)
        high_precision_count = parameter_count if counts_toward_rescue else 0
        total_parameter_count += parameter_count
        total_compressed_bits += compressed_bits
        total_high_precision_count += high_precision_count
        rows.append(
            {
                "name": name,
                "role": role,
                "parameter_count": int(parameter_count),
                "compressed_bits": int(compressed_bits),
                "compressed_size_bytes": int(math.ceil(compressed_bits / 8)),
                "bits_per_parameter": float(effective_bits_per_parameter),
                "high_precision_count": int(high_precision_count),
                "rescue_count": int(high_precision_count),
                "counts_toward_rescue": bool(counts_toward_rescue),
                **({"layer": str(entry["layer"])} if "layer" in entry else {}),
            }
        )
    return {
        "entries": rows,
        "parameter_count": int(total_parameter_count),
        "compressed_bits": int(total_compressed_bits),
        "high_precision_count": int(total_high_precision_count),
    }


def _scale_proxy_resource_count(proxy_count: int, reference_parameter_count: int) -> int:
    if reference_parameter_count <= 0:
        raise ValueError("reference_parameter_count must be positive")
    if proxy_count <= 0:
        return 0
    return int(math.ceil((int(proxy_count) * int(reference_parameter_count)) / max(1, TOTAL_WEIGHT_ELEMENTS)))


def _layer_plan_lookup(artifact: dict[str, Any]) -> dict[str, dict[str, Any]]:
    rows = artifact.get("layers")
    if not isinstance(rows, list):
        raise ValueError("artifact.layers must be a list")
    by_name: dict[str, dict[str, Any]] = {}
    for raw in rows:
        if not isinstance(raw, dict):
            raise ValueError("artifact.layers rows must be objects")
        name = str(raw.get("name") or "").strip()
        if not name:
            raise ValueError("artifact layer entry is missing a name")
        by_name[name] = dict(raw)
    return by_name


def _selected_rescue_values_for_plan(
    matrix: np.ndarray,
    *,
    mode: str,
    high_precision_fraction: float,
    scale_multiplier: float,
    binary_basis_count: int = 1,
    binary_basis_scales: list[float] | None = None,
) -> np.ndarray:
    flat = matrix.reshape(-1)
    keep_fraction = max(0.0, min(1.0, float(high_precision_fraction)))
    keep_count = int(round(len(flat) * keep_fraction))
    if keep_count <= 0:
        return np.asarray([], dtype=np.float64)
    basis_count = max(1, int(binary_basis_count))
    if mode == "binary" and basis_count > 1:
        provided_scales: list[float] | None = None
        if binary_basis_scales is not None:
            provided_scales = [float(value) for value in binary_basis_scales]
            if len(provided_scales) != basis_count:
                raise ValueError(
                    f"binary_basis_scales length {len(provided_scales)} does not match "
                    f"binary_basis_count {basis_count}"
                )
            if not all(math.isfinite(value) and value > 0.0 for value in provided_scales):
                raise ValueError("binary_basis_scales values must be finite positive numbers")
        residual = flat.copy()
        for basis_index in range(basis_count):
            scale = (
                (float(np.mean(np.abs(residual))) or 1.0) * max(0.25, float(scale_multiplier))
                if provided_scales is None
                else provided_scales[basis_index]
            )
            residual -= np.where(residual >= 0.0, scale, -scale)
        keep_indices = np.argpartition(np.abs(residual), -keep_count)[-keep_count:]
        return flat[keep_indices]
    keep_indices = np.argpartition(np.abs(flat), -keep_count)[-keep_count:]
    return flat[keep_indices]


def attach_q4_rescue_values_for_layer(
    plan: dict[str, Any],
    matrix: np.ndarray,
    *,
    mode: str,
    rescue_bits_per_parameter: float = DEFAULT_RESCUE_BITS_PER_PARAMETER,
) -> None:
    _validate_q4_rescue_bits(rescue_bits_per_parameter)
    values = _selected_rescue_values_for_plan(
        matrix,
        mode=mode,
        high_precision_fraction=float(plan.get("high_precision_fraction", 0.0)),
        scale_multiplier=float(plan.get("scale_multiplier", 1.0)),
        binary_basis_count=int(plan.get("binary_basis_count", 1)),
        binary_basis_scales=plan.get("binary_basis_scales"),
    )
    codes, scales, group_size = _encode_q4_rescue_payload(values)
    plan["rescue_quantization"] = Q4_RESCUE_QUANTIZATION
    plan["rescue_scale_group_size"] = int(group_size)
    plan["rescue_scales"] = scales
    plan.pop("rescue_scale", None)
    plan["rescue_values_q4"] = codes


def attach_q4_rescue_values(
    artifact: dict[str, Any],
    *,
    quant_mode: str,
    rescue_bits_per_parameter: float = DEFAULT_RESCUE_BITS_PER_PARAMETER,
) -> dict[str, Any]:
    plans = _layer_plan_lookup(artifact)
    for spec in _sorted_layer_specs():
        if spec.name not in plans:
            raise ValueError(f"artifact is missing layer: {spec.name}")
        attach_q4_rescue_values_for_layer(
            plans[spec.name],
            BASE_WEIGHTS[spec.name],
            mode=quant_mode,
            rescue_bits_per_parameter=rescue_bits_per_parameter,
        )
    rows = artifact.get("layers")
    if isinstance(rows, list):
        by_name = {str(row.get("name") or "").strip(): row for row in rows if isinstance(row, dict)}
        for name, plan in plans.items():
            if name in by_name:
                by_name[name].update(plan)
    return artifact


def _quantize_layer(
    matrix: np.ndarray,
    *,
    mode: str,
    high_precision_fraction: float,
    rescue_bits_per_parameter: float,
    scale_multiplier: float,
    threshold_multiplier: float,
    rescue_values_q4: Any = None,
    rescue_scales: Any = None,
    rescue_scale_group_size: Any = None,
    rescue_quantization: Any = None,
    layer_name: str = "layer",
    binary_basis_count: int = 1,
    binary_basis_scales: list[float] | None = None,
) -> tuple[np.ndarray, dict[str, Any]]:
    flat = matrix.reshape(-1)
    keep_fraction = max(0.0, min(1.0, float(high_precision_fraction)))
    keep_count = int(round(len(flat) * keep_fraction))
    basis_count = max(1, int(binary_basis_count))

    if mode == "binary" and basis_count > 1:
        provided_scales: list[float] | None = None
        if binary_basis_scales is not None:
            provided_scales = [float(value) for value in binary_basis_scales]
            if len(provided_scales) != basis_count:
                raise ValueError(
                    f"binary_basis_scales length {len(provided_scales)} does not match "
                    f"binary_basis_count {basis_count}"
                )
            if not all(math.isfinite(value) and value > 0.0 for value in provided_scales):
                raise ValueError("binary_basis_scales values must be finite positive numbers")
        candidate = np.zeros_like(flat)
        residual = flat.copy()
        scales: list[float] = []
        for basis_index in range(basis_count):
            if provided_scales is None:
                scale = (float(np.mean(np.abs(residual))) or 1.0) * max(0.25, float(scale_multiplier))
            else:
                scale = provided_scales[basis_index]
            basis = np.where(residual >= 0.0, scale, -scale)
            candidate += basis
            residual -= basis
            scales.append(float(scale))
        keep_indices = np.array([], dtype=np.int64)
        if keep_count > 0:
            keep_indices = np.argpartition(np.abs(residual), -keep_count)[-keep_count:]
            candidate[keep_indices] = _decode_q4_rescue_payload(
                raw_values=rescue_values_q4,
                raw_scales=rescue_scales,
                raw_scale_group_size=rescue_scale_group_size,
                raw_quantization=rescue_quantization,
                expected_count=keep_count,
                bits_per_parameter=rescue_bits_per_parameter,
                source=f"artifact.layers[{layer_name}]",
            )
        quantized = candidate.reshape(matrix.shape)
        rescue_compressed_bits = int(math.ceil(keep_count * rescue_bits_per_parameter))
        rescue_scale_bits = _q4_rescue_scale_bits(keep_count)
        compressed_bits = (len(flat) * basis_count) + rescue_compressed_bits + (64 * basis_count) + rescue_scale_bits
        quantized_parameter_count = len(flat) * basis_count
        side_parameter_count = basis_count
        parameter_count = quantized_parameter_count + keep_count + side_parameter_count
        summary = {
            "high_precision_fraction": float(keep_count / max(1, len(flat))),
            "high_precision_count": int(keep_count),
            "rescue_fraction": float(keep_count / max(1, len(flat))),
            "rescue_count": int(keep_count),
            "rescue_bits_per_parameter": float(rescue_bits_per_parameter),
            "rescue_compressed_bits": int(rescue_compressed_bits),
            "rescue_scale_bits": int(rescue_scale_bits),
            "quantized_parameter_count": int(quantized_parameter_count),
            "side_parameter_count": int(side_parameter_count),
            "parameter_count": int(parameter_count),
            "compressed_bits": int(compressed_bits),
            "compressed_size_bytes": int(math.ceil(compressed_bits / 8)),
            "scale": float(scales[0] if scales else 1.0),
            "scales": scales,
            "binary_basis_count": int(basis_count),
            "threshold": 0.0,
            "zero_count": 0,
        }
        return quantized, summary

    keep_indices = np.array([], dtype=np.int64)
    if keep_count > 0:
        keep_indices = np.argpartition(np.abs(flat), -keep_count)[-keep_count:]
    keep_mask = np.zeros((len(flat),), dtype=bool)
    if keep_indices.size:
        keep_mask[keep_indices] = True

    candidate = np.zeros_like(flat)
    if np.any(~keep_mask):
        quantized_source = flat[~keep_mask]
        abs_mean = float(np.mean(np.abs(quantized_source))) or 1.0
        scale = abs_mean * max(0.25, float(scale_multiplier))
        if mode == "binary":
            candidate[~keep_mask] = np.where(quantized_source >= 0.0, scale, -scale)
            zero_count = 0
            quant_bits = 1
        elif mode == "ternary":
            threshold = abs_mean * max(0.10, float(threshold_multiplier))
            signs = np.where(quantized_source >= 0.0, scale, -scale)
            candidate[~keep_mask] = np.where(np.abs(quantized_source) >= threshold, signs, 0.0)
            zero_count = int(np.sum(candidate[~keep_mask] == 0.0))
            quant_bits = 2
        else:
            raise ValueError(f"unsupported quant mode: {mode}")
    else:
        scale = 1.0
        threshold = 0.0
        zero_count = 0
        quant_bits = 1 if mode == "binary" else 2

    candidate[keep_mask] = flat[keep_mask]
    if keep_indices.size:
        candidate[keep_indices] = _decode_q4_rescue_payload(
            raw_values=rescue_values_q4,
            raw_scales=rescue_scales,
            raw_scale_group_size=rescue_scale_group_size,
            raw_quantization=rescue_quantization,
            expected_count=keep_count,
            bits_per_parameter=rescue_bits_per_parameter,
            source=f"artifact.layers[{layer_name}]",
        )
    quantized = candidate.reshape(matrix.shape)
    rescue_compressed_bits = int(math.ceil(keep_count * rescue_bits_per_parameter))
    rescue_scale_bits = _q4_rescue_scale_bits(keep_count)
    compressed_bits = ((len(flat) - keep_count) * quant_bits) + rescue_compressed_bits + 64 + rescue_scale_bits
    quantized_parameter_count = len(flat) - keep_count
    side_parameter_count = 1
    parameter_count = quantized_parameter_count + keep_count + side_parameter_count
    summary = {
        "high_precision_fraction": float(keep_count / max(1, len(flat))),
        "high_precision_count": int(keep_count),
        "rescue_fraction": float(keep_count / max(1, len(flat))),
        "rescue_count": int(keep_count),
        "rescue_bits_per_parameter": float(rescue_bits_per_parameter),
        "rescue_compressed_bits": int(rescue_compressed_bits),
        "rescue_scale_bits": int(rescue_scale_bits),
        "quantized_parameter_count": int(quantized_parameter_count),
        "side_parameter_count": int(side_parameter_count),
        "parameter_count": int(parameter_count),
        "compressed_bits": int(compressed_bits),
        "compressed_size_bytes": int(math.ceil(compressed_bits / 8)),
        "scale": float(scale),
        "binary_basis_count": int(basis_count if mode == "binary" else 1),
        "threshold": float(threshold if mode == "ternary" else 0.0),
        "zero_count": int(zero_count),
    }
    return quantized, summary


def build_candidate_weights(config: BenchmarkConfig, artifact: dict[str, Any]) -> tuple[dict[str, np.ndarray], dict[str, Any]]:
    reference_limits = _reference_limits(config)
    plans = _layer_plan_lookup(artifact)
    candidate: dict[str, np.ndarray] = {}
    layer_summaries: list[dict[str, Any]] = []
    total_high_precision_count = 0
    total_compressed_bits = 0
    total_parameter_count = 0
    for spec in _sorted_layer_specs():
        if spec.name not in plans:
            raise ValueError(f"artifact is missing layer: {spec.name}")
        plan = plans[spec.name]
        declared_shape = tuple(int(value) for value in plan.get("shape", spec.shape))
        if declared_shape != spec.shape:
            raise ValueError(f"shape mismatch for {spec.name}: {declared_shape} != {spec.shape}")
        quantized, summary = _quantize_layer(
            BASE_WEIGHTS[spec.name],
            mode=config.quant_mode,
            high_precision_fraction=float(plan.get("high_precision_fraction", 0.0)),
            rescue_bits_per_parameter=float(reference_limits.rescue_bits_per_parameter),
            scale_multiplier=float(plan.get("scale_multiplier", 1.0)),
            threshold_multiplier=float(plan.get("threshold_multiplier", 0.80)),
            rescue_values_q4=plan.get("rescue_values_q4"),
            rescue_scales=plan.get("rescue_scales"),
            rescue_scale_group_size=plan.get("rescue_scale_group_size"),
            rescue_quantization=plan.get("rescue_quantization"),
            layer_name=spec.name,
            binary_basis_count=int(plan.get("binary_basis_count", 1)),
            binary_basis_scales=plan.get("binary_basis_scales"),
        )
        candidate[spec.name] = quantized
        total_high_precision_count += int(summary["high_precision_count"])
        total_compressed_bits += int(summary["compressed_bits"])
        total_parameter_count += int(summary["parameter_count"])
        layer_summaries.append(
            {
                "name": spec.name,
                "shape": list(spec.shape),
                **summary,
            }
        )
    extra_accounting = _summarize_extra_accounting_entries(_accounting_entries_from_artifact(artifact, plans))
    for entry in extra_accounting["entries"]:
        if bool(entry.get("counts_toward_rescue")) and float(entry.get("bits_per_parameter") or 0.0) > (
            reference_limits.effective_rescue_bits_per_parameter + 1e-12
        ):
            raise ValueError(
                f"artifact accounting entry {entry['name']} exceeds q4 rescue budget: "
                f"bits_per_parameter={float(entry.get('bits_per_parameter') or 0.0):.12g}"
            )
    total_high_precision_count += int(extra_accounting["high_precision_count"])
    total_compressed_bits += int(extra_accounting["compressed_bits"])
    total_parameter_count += int(extra_accounting["parameter_count"])
    proxy_total_high_precision_count = int(total_high_precision_count)
    proxy_compressed_bits = int(total_compressed_bits)
    proxy_parameter_count = int(total_parameter_count)
    scaled_high_precision_count = _scale_proxy_resource_count(
        proxy_total_high_precision_count,
        reference_limits.parameter_count,
    )
    scaled_compressed_bits = _scale_proxy_resource_count(proxy_compressed_bits, reference_limits.parameter_count)
    scaled_parameter_count = _scale_proxy_resource_count(proxy_parameter_count, reference_limits.parameter_count)
    overall_high_precision_fraction = proxy_total_high_precision_count / max(1, TOTAL_WEIGHT_ELEMENTS)
    proxy_high_precision_fraction = overall_high_precision_fraction
    compressed_size_bytes = int(math.ceil(scaled_compressed_bits / 8))
    summary = {
        "layers": layer_summaries,
        "extra_accounting_entries": extra_accounting["entries"],
        "total_high_precision_count": int(scaled_high_precision_count),
        "total_rescue_count": int(scaled_high_precision_count),
        "proxy_high_precision_count": int(proxy_total_high_precision_count),
        "proxy_rescue_count": int(proxy_total_high_precision_count),
        "overall_high_precision_fraction": float(overall_high_precision_fraction),
        "overall_rescue_fraction": float(overall_high_precision_fraction),
        "proxy_high_precision_fraction": float(proxy_high_precision_fraction),
        "proxy_rescue_fraction": float(proxy_high_precision_fraction),
        "parameter_count": int(scaled_parameter_count),
        "proxy_accounted_parameter_count": int(proxy_parameter_count),
        "parameter_count_multiplier": float(scaled_parameter_count / max(1, reference_limits.parameter_count)),
        "proxy_parameter_count_multiplier": float(proxy_parameter_count / max(1, TOTAL_WEIGHT_ELEMENTS)),
        "compressed_bits": int(scaled_compressed_bits),
        "proxy_compressed_bits": int(proxy_compressed_bits),
        "compressed_size_bytes": int(compressed_size_bytes),
        "proxy_compressed_size_bytes": int(math.ceil(proxy_compressed_bits / 8)),
        "compression_ratio": float(reference_limits.baseline_bits / max(1, scaled_compressed_bits)),
        "baseline_parameter_count": int(reference_limits.parameter_count),
        "baseline_bits": int(reference_limits.baseline_bits),
        "baseline_size_bytes": int(reference_limits.baseline_size_bytes),
        "max_parameter_count": int(reference_limits.max_parameter_count),
        "max_compressed_bits": int(reference_limits.max_compressed_bits),
        "reference_model_id": reference_limits.model_id,
        "native_bits_per_parameter": float(reference_limits.native_bits_per_parameter),
        "max_non_native_fraction": float(reference_limits.max_non_native_fraction),
        "max_rescue_fraction": float(reference_limits.max_non_native_fraction),
        "rescue_bits_per_parameter": float(reference_limits.rescue_bits_per_parameter),
        "rescue_quantization": Q4_RESCUE_QUANTIZATION,
        "rescue_scale_bits": int(reference_limits.rescue_scale_bits),
        "rescue_scale_group_size": int(reference_limits.rescue_scale_group_size),
        "effective_rescue_bits_per_parameter": float(reference_limits.effective_rescue_bits_per_parameter),
        "proxy_model_id": MODEL_ID,
        "proxy_parameter_count": int(TOTAL_WEIGHT_ELEMENTS),
    }
    _validate_declared_accounting(artifact, summary)
    return candidate, summary


