@dataclass(frozen=True, slots=True)
class LayerSpec:
    name: str
    rows: int
    cols: int

    @property
    def shape(self) -> tuple[int, int]:
        return (self.rows, self.cols)

    @property
    def element_count(self) -> int:
        return self.rows * self.cols


