def _seed_from_text(value: str) -> int:
    digest = hashlib.sha256(value.encode("utf-8")).digest()
    return int.from_bytes(digest[:8], byteorder="big", signed=False)


def _sorted_layer_specs() -> tuple[LayerSpec, ...]:
    return LAYER_SPECS


def _make_base_weights() -> dict[str, np.ndarray]:
    rng = np.random.default_rng(PACK_SEED)
    weights: dict[str, np.ndarray] = {}
    for spec in _sorted_layer_specs():
        scale = 0.11 if spec.name == "lm_head" else 0.08
        weights[spec.name] = rng.normal(0.0, scale, size=spec.shape).astype(np.float64)
    return weights


BASE_WEIGHTS = _make_base_weights()
TOTAL_WEIGHT_ELEMENTS = sum(spec.element_count for spec in _sorted_layer_specs())
TOTAL_BASELINE_BITS = TOTAL_WEIGHT_ELEMENTS * BASELINE_REFERENCE_BITS
TOTAL_BASELINE_BYTES = math.ceil(TOTAL_BASELINE_BITS / 8)
MAX_COMPRESSED_BITS = TOTAL_BASELINE_BITS
MAX_PARAMETER_COUNT = TOTAL_WEIGHT_ELEMENTS * MAX_PARAMETER_COUNT_MULTIPLIER


def _default_native_bits(quant_mode: str) -> float:
    if quant_mode == "binary":
        return 1.0
    if quant_mode == "ternary":
        return 2.0
    return float(BASELINE_REFERENCE_BITS)


def _reference_limits(config: BenchmarkConfig) -> ReferenceLimits:
    rescue_bits_per_parameter = float(config.rescue_bits_per_parameter)
    if not math.isfinite(rescue_bits_per_parameter) or rescue_bits_per_parameter <= 0.0:
        raise ValueError("rescue_bits_per_parameter must be positive and finite")
    rescue_scale_bits = int(Q4_RESCUE_SCALE_BITS)
    rescue_scale_group_size = int(Q4_RESCUE_SCALE_GROUP_SIZE)
    effective_rescue_bits_per_parameter = rescue_bits_per_parameter + (
        rescue_scale_bits / float(rescue_scale_group_size)
    )
    if config.reference_parameter_count is None:
        return ReferenceLimits(
            model_id=MODEL_ID,
            parameter_count=int(TOTAL_WEIGHT_ELEMENTS),
            baseline_bits=int(TOTAL_BASELINE_BITS),
            baseline_size_bytes=int(TOTAL_BASELINE_BYTES),
            max_parameter_count=int(MAX_PARAMETER_COUNT),
            max_compressed_bits=int(MAX_COMPRESSED_BITS),
            native_bits_per_parameter=_default_native_bits(config.quant_mode),
            max_non_native_fraction=float(MAX_HIGH_PRECISION_FRACTION),
            rescue_bits_per_parameter=rescue_bits_per_parameter,
            rescue_scale_bits=rescue_scale_bits,
            rescue_scale_group_size=rescue_scale_group_size,
            effective_rescue_bits_per_parameter=effective_rescue_bits_per_parameter,
        )

    reference_parameter_count = int(config.reference_parameter_count)
    if reference_parameter_count <= 0:
        raise ValueError("reference_parameter_count must be positive")
    native_bits_per_parameter = (
        _default_native_bits(config.quant_mode)
        if config.native_bits_per_parameter is None
        else float(config.native_bits_per_parameter)
    )
    if not math.isfinite(native_bits_per_parameter) or native_bits_per_parameter <= 0.0:
        raise ValueError("native_bits_per_parameter must be positive and finite")
    max_non_native_fraction = float(config.max_non_native_fraction)
    if not math.isfinite(max_non_native_fraction) or not 0.0 <= max_non_native_fraction <= 1.0:
        raise ValueError("max_non_native_fraction must be in [0, 1]")

    baseline_bits = reference_parameter_count * BASELINE_REFERENCE_BITS
    max_compressed_bits = int(
        math.ceil(
            reference_parameter_count
            * (
                ((1.0 - max_non_native_fraction) * native_bits_per_parameter)
                + (max_non_native_fraction * effective_rescue_bits_per_parameter)
            )
        )
    )
    return ReferenceLimits(
        model_id=config.reference_model_id or MODEL_ID,
        parameter_count=reference_parameter_count,
        baseline_bits=int(baseline_bits),
        baseline_size_bytes=int(math.ceil(baseline_bits / 8)),
        max_parameter_count=int(reference_parameter_count * MAX_PARAMETER_COUNT_MULTIPLIER),
        max_compressed_bits=max_compressed_bits,
        native_bits_per_parameter=float(native_bits_per_parameter),
        max_non_native_fraction=max_non_native_fraction,
        rescue_bits_per_parameter=rescue_bits_per_parameter,
        rescue_scale_bits=rescue_scale_bits,
        rescue_scale_group_size=rescue_scale_group_size,
        effective_rescue_bits_per_parameter=effective_rescue_bits_per_parameter,
    )


def _document_matrix(documents: list[str]) -> np.ndarray:
    rows: list[np.ndarray] = []
    for text in documents:
        counts = np.zeros((INPUT_DIM,), dtype=np.float64)
        tokens = [token for token in text.lower().split() if token in TOKEN_TO_ID]
        for token in tokens:
            counts[TOKEN_TO_ID[token]] += 1.0
        if tokens:
            counts /= max(1, len(tokens))
        rows.append(counts)
    if not rows:
        raise RuntimeError("no documents selected for benchmark shard")
    return np.stack(rows, axis=0)


def _positive_int_env(name: str, default: int) -> int:
    raw_value = str(os.environ.get(name) or "").strip()
    if not raw_value:
        return default
    try:
        parsed = int(raw_value)
    except ValueError:
        return default
    return parsed if parsed > 0 else default


def _submission_artifact_path() -> Path:
    raw_path = str(os.environ.get("AUTORESEARCH_SUBMISSION_ARTIFACT_PATH") or "").strip()
    if not raw_path:
        raise RuntimeError("AUTORESEARCH_SUBMISSION_ARTIFACT_PATH is required for direct model evaluation")
    path = Path(raw_path).expanduser()
    if not path.is_absolute():
        path = Path.cwd() / path
    if not path.exists():
        raise RuntimeError(f"submission artifact not found: {path}")
    return path.resolve()


def _path_size_bytes(path: Path) -> int:
    if path.is_file():
        return int(path.stat().st_size)
    total = 0
    for child in path.rglob("*"):
        if child.is_file():
            total += int(child.stat().st_size)
    return total


def _downloaded_artifact_size_bytes(path: Path) -> int:
    raw_size = str(os.environ.get("AUTORESEARCH_SUBMISSION_ARTIFACT_BYTES") or "").strip()
    if raw_size:
        try:
            parsed = int(raw_size)
        except ValueError as exc:
            raise RuntimeError("AUTORESEARCH_SUBMISSION_ARTIFACT_BYTES must be an integer") from exc
        if parsed <= 0:
            raise RuntimeError("AUTORESEARCH_SUBMISSION_ARTIFACT_BYTES must be positive")
        return parsed
    return _path_size_bytes(path)


def _safe_archive_target(root: Path, member_name: str) -> Path:
    target = (root / member_name).resolve()
    try:
        target.relative_to(root.resolve())
    except ValueError as exc:
        raise RuntimeError(f"unsafe archive path: {member_name}") from exc
    return target


def _extract_zip_artifact(artifact_path: Path, dest: Path) -> None:
    with zipfile.ZipFile(artifact_path) as archive:
        for member in archive.infolist():
            _safe_archive_target(dest, member.filename)
        archive.extractall(dest)


def _extract_tar_artifact(artifact_path: Path, dest: Path) -> None:
    with tarfile.open(artifact_path) as archive:
        for member in archive.getmembers():
            _safe_archive_target(dest, member.name)
        archive.extractall(dest)


def _materialize_model_artifact(artifact_path: Path, work_dir: Path) -> Path:
    if artifact_path.is_dir():
        return artifact_path
    if zipfile.is_zipfile(artifact_path):
        root = work_dir / "artifact"
        root.mkdir(parents=True, exist_ok=True)
        _extract_zip_artifact(artifact_path, root)
        return root
    if tarfile.is_tarfile(artifact_path):
        root = work_dir / "artifact"
        root.mkdir(parents=True, exist_ok=True)
        _extract_tar_artifact(artifact_path, root)
        return root
    if str(os.environ.get("AUTORESEARCH_ALLOW_DIRECT_EVAL_STUB") or "").strip().lower() in {"1", "true", "yes"}:
        return artifact_path
    raise RuntimeError("submission artifact must be a Hugging Face model directory, .zip, or tar archive")


def _find_hf_model_dir(root: Path) -> Path:
    if root.is_file():
        return root
    candidates = [root, *[child for child in root.rglob("*") if child.is_dir()]]
    for candidate in candidates:
        if (candidate / "config.json").is_file():
            return candidate
    raise RuntimeError(f"submission artifact does not contain a Hugging Face config.json: {root}")


def _artifact_budget_bits(*, parameter_count: int, reference_limits: ReferenceLimits) -> int:
    if parameter_count <= 0:
        raise RuntimeError("loaded model parameter_count must be positive")
    per_parameter_budget = (
        ((1.0 - reference_limits.max_non_native_fraction) * reference_limits.native_bits_per_parameter)
        + (reference_limits.max_non_native_fraction * reference_limits.effective_rescue_bits_per_parameter)
    )
    return int(math.ceil(parameter_count * per_parameter_budget))


def _load_direct_eval_stub(artifact_path: Path) -> dict[str, Any] | None:
    if str(os.environ.get("AUTORESEARCH_ALLOW_DIRECT_EVAL_STUB") or "").strip().lower() not in {"1", "true", "yes"}:
        return None
    if not artifact_path.is_file():
        return None
    try:
        payload = json.loads(artifact_path.read_text(encoding="utf-8"))
    except Exception:
        return None
    if not isinstance(payload, dict) or payload.get("artifact_type") != "autoresearch-direct-eval-stub":
        return None
    return payload


class _DirectEvalLogitsCoverageError(RuntimeError):
    def __init__(self, *, logits_shape: tuple[int, ...], input_shape: tuple[int, ...]) -> None:
        self.logits_shape = logits_shape
        self.input_shape = input_shape
        super().__init__(
            "direct model evaluation logits shape does not cover input tokens: "
            f"logits_shape={logits_shape} input_shape={input_shape}"
        )


def _score_transformer_model(*, model_dir: Path, documents: list[str]) -> dict[str, Any]:
    try:
        import torch
        import torch.nn.functional as torch_functional
        from transformers import AutoModelForCausalLM, AutoTokenizer
    except Exception as exc:  # pragma: no cover - depends on validator CUDA image dependencies
        raise RuntimeError("direct model evaluation requires torch and transformers") from exc

    device_name = str(os.environ.get("AUTORESEARCH_EVAL_DEVICE") or ("cuda" if torch.cuda.is_available() else "cpu"))
    device = torch.device(device_name)
    max_tokens = _positive_int_env("AUTORESEARCH_EVAL_MAX_TOKENS", 512)
    batch_size = _positive_int_env("AUTORESEARCH_EVAL_BATCH_SIZE", 8)
    local_files_only = str(os.environ.get("AUTORESEARCH_EVAL_LOCAL_FILES_ONLY") or "1").strip().lower() not in {
        "0",
        "false",
        "no",
    }
    device_map_raw = str(os.environ.get("AUTORESEARCH_EVAL_DEVICE_MAP") or "").strip()
    use_device_map = bool(device_map_raw)
    eval_tokenizer_id = str(os.environ.get("AUTORESEARCH_EVAL_TOKENIZER_ID") or TOKENIZER_ID).strip()
    if not eval_tokenizer_id:
        raise RuntimeError("direct model evaluation requires a validator tokenizer id")
    tokenizer = AutoTokenizer.from_pretrained(
        eval_tokenizer_id,
        trust_remote_code=False,
        local_files_only=local_files_only,
    )
    dtype = torch.float16 if device.type == "cuda" else torch.float32
    model_kwargs: dict[str, Any] = {
        "trust_remote_code": True,
        "local_files_only": local_files_only,
        "torch_dtype": dtype,
        "low_cpu_mem_usage": True,
    }
    if device_map_raw:
        model_kwargs["device_map"] = device_map_raw
    model = AutoModelForCausalLM.from_pretrained(str(model_dir), **model_kwargs)
    if not use_device_map:
        model.to(device)
    model.eval()
    input_device = next(model.parameters()).device

    pad_token_id = 0
    for attr_name in ("pad_token_id", "eos_token_id", "bos_token_id"):
        raw_pad_token_id = getattr(tokenizer, attr_name, None)
        if raw_pad_token_id is None:
            continue
        try:
            pad_token_id = int(raw_pad_token_id)
        except (TypeError, ValueError):
            continue
        break

    tokenized_documents: list[tuple[Any, Any]] = []
    scored_docs = 0
    for text in documents:
        encoded = tokenizer(
            text,
            return_tensors="pt",
            truncation=True,
            max_length=max_tokens,
        )
        input_ids = encoded["input_ids"].reshape(-1)
        attention_mask_raw = encoded.get("attention_mask")
        attention_mask = attention_mask_raw.reshape(-1) if attention_mask_raw is not None else torch.ones_like(input_ids)
        token_count = int(input_ids.shape[0])
        if token_count < 2:
            continue
        target_count = int(attention_mask[1:].sum().detach().cpu())
        if target_count <= 0:
            continue
        tokenized_documents.append((input_ids, attention_mask))
        scored_docs += 1

    total_nll = 0.0
    total_tokens = 0
    chunked_eval = False
    eval_chunk_tokens: int | None = None
    eval_chunk_count = 0

    def _score_model_window(input_window: Any, attention_window: Any) -> tuple[float, int, int]:
        window_tokens = int(input_window.shape[1])
        output = model(input_ids=input_window, attention_mask=attention_window)
        logits = getattr(output, "logits", None)
        if logits is None:
            raise RuntimeError("direct model evaluation requires model output logits")
        if int(logits.ndim) != 3:
            raise RuntimeError(f"direct model evaluation expected rank-3 logits, got rank {int(logits.ndim)}")
        if int(logits.shape[0]) != int(input_window.shape[0]) or int(logits.shape[1]) < window_tokens:
            raise _DirectEvalLogitsCoverageError(
                logits_shape=tuple(logits.shape),
                input_shape=tuple(input_window.shape),
            )
        vocab_size = int(logits.shape[-1])
        shifted_logits = logits[:, : window_tokens - 1, :].contiguous()
        shifted_labels = input_window[:, 1:window_tokens].contiguous().long()
        shifted_mask = attention_window[:, 1:window_tokens].contiguous().bool()
        label_count = int(shifted_mask.sum().detach().cpu())
        if label_count <= 0:
            return 0.0, 0, vocab_size
        valid_labels = shifted_labels[shifted_mask]
        min_label = int(valid_labels.min().detach().cpu())
        max_label = int(valid_labels.max().detach().cpu())
        if min_label < 0 or max_label >= vocab_size:
            raise RuntimeError(
                "direct model evaluation target token id outside logits vocabulary: "
                f"min_label={min_label} max_label={max_label} vocab_size={vocab_size}"
            )
        masked_labels = shifted_labels.masked_fill(~shifted_mask, -100)
        batch_nll = torch_functional.cross_entropy(
            shifted_logits.reshape(-1, vocab_size).float(),
            masked_labels.reshape(-1),
            ignore_index=-100,
            reduction="sum",
        )
        if not bool(torch.isfinite(batch_nll).detach().cpu()):
            raise RuntimeError("direct model evaluation produced non-finite cross entropy")
        return float(batch_nll.detach().cpu()), label_count, vocab_size

    with torch.no_grad():
        for batch_start in range(0, len(tokenized_documents), batch_size):
            batch_documents = tokenized_documents[batch_start : batch_start + batch_size]
            batch_rows = len(batch_documents)
            batch_max_tokens = max(int(input_ids.shape[0]) for input_ids, _attention_mask in batch_documents)
            input_batch = torch.full(
                (batch_rows, batch_max_tokens),
                int(pad_token_id),
                dtype=torch.long,
                device=input_device,
            )
            attention_batch = torch.zeros(
                (batch_rows, batch_max_tokens),
                dtype=torch.long,
                device=input_device,
            )
            for row_index, (input_ids, attention_mask) in enumerate(batch_documents):
                token_count = int(input_ids.shape[0])
                input_batch[row_index, :token_count] = input_ids.to(input_device)
                attention_batch[row_index, :token_count] = attention_mask.to(input_device)

            try:
                batch_nll, label_count, _vocab_size = _score_model_window(input_batch, attention_batch)
                eval_chunk_count += 1
            except _DirectEvalLogitsCoverageError as exc:
                short_tokens = int(exc.logits_shape[1]) if len(exc.logits_shape) >= 2 else 0
                if short_tokens < 2:
                    raise
                chunked_eval = True
                eval_chunk_tokens = short_tokens if eval_chunk_tokens is None else min(eval_chunk_tokens, short_tokens)
                batch_nll = 0.0
                label_count = 0
                target_start = 1
                while target_start < batch_max_tokens:
                    context_start = target_start - 1
                    context_end = min(context_start + short_tokens, batch_max_tokens)
                    chunk_input = input_batch[:, context_start:context_end]
                    chunk_attention = attention_batch[:, context_start:context_end]
                    chunk_nll, chunk_labels, _vocab_size = _score_model_window(chunk_input, chunk_attention)
                    batch_nll += chunk_nll
                    label_count += chunk_labels
                    eval_chunk_count += 1
                    target_start = context_end
            if label_count <= 0:
                continue
            total_nll += batch_nll
            total_tokens += label_count
    if total_tokens <= 0:
        raise RuntimeError("direct model evaluation produced no scored tokens")
    mean_nll = float(total_nll / total_tokens)
    return {
        "heldout_ppl": float(math.exp(min(mean_nll, 700.0))),
        "heldout_cross_entropy_nats": mean_nll,
        "scored_docs": scored_docs,
        "token_count": total_tokens,
        "max_tokens_per_doc": max_tokens,
        "batch_size": batch_size,
        "parameter_count": int(sum(parameter.numel() for parameter in model.parameters())),
        "tokenizer_id": eval_tokenizer_id,
        "device": str(input_device),
        "dtype": "fp16" if dtype == torch.float16 else "fp32",
        "chunked_eval": chunked_eval,
        "eval_chunk_tokens": eval_chunk_tokens or max_tokens,
        "eval_chunk_count": eval_chunk_count,
    }


def _effective_rotation_key(rotation_key: str) -> str:
    base_key = str(rotation_key or "default-rotation").strip() or "default-rotation"
    sync_slot = str(os.environ.get("AUTORESEARCH_HELDOUT_SYNC_SLOT") or "").strip()
    sync_number = str(os.environ.get("AUTORESEARCH_HELDOUT_SYNC_NUMBER") or "").strip()
    if not sync_slot and not sync_number:
        return base_key
    return f"{base_key}:slot={sync_slot}:sync={sync_number}"


def _parse_dataset_mix(dataset_mix: str) -> list[tuple[str, float]]:
    rows: list[tuple[str, float]] = []
    for part in str(dataset_mix or "").split(","):
        key, separator, weight_raw = part.strip().partition(":")
        key = key.strip().lower()
        if not key or not separator:
            continue
        try:
            weight = float(weight_raw)
        except ValueError:
            continue
        if math.isfinite(weight) and weight > 0.0:
            rows.append((key, weight))
    return rows


def _is_private_dataset_handle(dataset_name: str) -> bool:
    key = str(dataset_name or "").strip().lower()
    return key in PRIVATE_HELDOUT_ALIASES or key.startswith(("private://", "hf://"))


def _private_manifest_root(manifest_path: Path) -> Path:
    raw_root = str(os.environ.get(PRIVATE_HELDOUT_ROOT_ENV) or "").strip()
    if raw_root:
        return Path(raw_root).expanduser().resolve()
    return manifest_path.parent.resolve()


def _private_manifest_entries_for_selector(data: Any, selector: str) -> list[Any]:
    key = str(selector or "").strip().lower()
    if isinstance(data, list):
        return list(data)
    if not isinstance(data, dict):
        raise RuntimeError("private heldout manifest must be a JSON object or list")

    for section_name in ("datasets", "categories"):
        section = data.get(section_name)
        if isinstance(section, dict):
            if key in section:
                entries = section[key]
                return list(entries if isinstance(entries, list) else [entries])
            for raw_name, entries in section.items():
                if str(raw_name or "").strip().lower() == key:
                    return list(entries if isinstance(entries, list) else [entries])

    entries = data.get("documents", [])
    return list(entries if isinstance(entries, list) else [entries])


def _load_manifest_data(path: Path) -> Any:
    suffix = path.suffix.lower()
    raw = path.read_text(encoding="utf-8")
    if suffix == ".jsonl":
        rows: list[Any] = []
        for line in raw.splitlines():
            stripped = line.strip()
            if not stripped:
                continue
            try:
                rows.append(json.loads(stripped))
            except json.JSONDecodeError:
                rows.append(stripped)
        return rows
    if suffix in {".txt", ".text"}:
        return [line.strip() for line in raw.splitlines() if line.strip()]
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"private heldout manifest is invalid JSON: {path}") from exc


def _manifest_entry_matches_selector(entry: Any, selector: str) -> bool:
    key = str(selector or "").strip().lower()
    if not key or _is_private_dataset_handle(key):
        return True
    if not isinstance(entry, dict):
        return False
    raw_values = [
        entry.get("dataset"),
        entry.get("category"),
        *(entry.get("datasets") if isinstance(entry.get("datasets"), list) else []),
        *(entry.get("categories") if isinstance(entry.get("categories"), list) else []),
        *(entry.get("tags") if isinstance(entry.get("tags"), list) else []),
    ]
    return any(str(value or "").strip().lower() == key for value in raw_values)


def _normalise_relative_hf_path(raw_path: str) -> str:
    path = str(raw_path or "").strip().lstrip("/")
    if not path or path.startswith("../") or "/../" in path or path == "..":
        raise RuntimeError("private heldout HF document path must be relative and stay inside the dataset repo")
    return path


def _positive_int_value(value: Any, default: int, *, max_value: int | None = None) -> int:
    try:
        parsed = int(value)
    except (TypeError, ValueError):
        parsed = default
    parsed = parsed if parsed > 0 else default
    if max_value is not None:
        parsed = min(parsed, max_value)
    return parsed


def _text_from_value(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, (int, float, bool)):
        return str(value)
    if isinstance(value, list):
        return "\n".join(part for part in (_text_from_value(item) for item in value) if part)
    if isinstance(value, dict):
        return "\n".join(
            part
            for part in (_text_from_value(value[key]) for key in sorted(value))
            if part
        )
    return str(value)


